import { chromium, expect } from '@playwright/test';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const root = 'https://app.grasskickz.com';
const output = 'review/atlas-public-release-20260913';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 1600, height: 1000 }, geolocation: { latitude: 41.714, longitude: 44.778 } });
const page = await context.newPage();
page.setDefaultTimeout(30000);
const errors = [], queries = [];
page.on('pageerror', error => errors.push(error.message));
page.on('request', request => { if (new URL(request.url()).pathname === '/api/map/nearby') queries.push(request.url()); });
try {
  const html = await readFile('dist/map-atlas-release-20260913/index.html', 'utf8');
  const asset = html.match(/src="([^"]+\.js)"/)[1];
  const response = await context.request.get(root + asset);
  expect(response.status()).toBe(200);
  const hash = data => createHash('sha256').update(data).digest('hex');
  expect(hash(await response.body())).toBe(hash(await readFile('dist/map-atlas-release-20260913' + asset)));
  await page.goto(root + '/world');
  await expect(page.getByRole('button', { name: 'Toggle nearby results' })).toBeVisible();
  const filters = page.getByLabel('Simple map filters');
  if (!await filters.isVisible()) await page.getByRole('button', { name: /filter/i }).first().click();
  await expect(filters).toBeVisible();
  await context.grantPermissions(['geolocation']);
  await page.getByRole('button', { name: 'Use my location', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Search origin' })).toContainText('41.71400, 44.77800');
  await page.getByRole('button', { name: 'Within radius', exact: true }).click();
  await page.getByRole('button', { name: '400 km', exact: true }).click();
  await page.getByRole('button', { name: 'Show results', exact: true }).click();
  const list = page.getByRole('complementary', { name: 'Nearby results' });
  if (!await list.isVisible()) await page.getByRole('button', { name: 'Toggle nearby results' }).click();
  await expect(list.getByRole('listitem')).toHaveCount(14);
  const first = list.getByRole('listitem').first();
  await first.click({ position: { x: 8, y: 8 } });
  await expect(first.locator('.atlas-result-main')).toHaveAttribute('aria-pressed', 'true');
  await expect(list).toBeVisible();
  await page.waitForTimeout(2000);
  await page.screenshot({ path: output + '/public-map.png' });
  await page.getByRole('button', { name: 'Search visible map', exact: true }).click();
  await expect(list.getByRole('status')).toContainText('Searched map area');
  await page.waitForTimeout(1500);
  const areaCount = await list.getByRole('listitem').count();
  await page.getByRole('button', { name: 'Show results', exact: true }).click();
  await page.waitForTimeout(1500);
  await expect(list.getByRole('listitem')).toHaveCount(areaCount);
  expect(errors).toEqual([]);
  const report = { passed: true, root, asset, radiusCount: 14, areaCount, cardFocus: true, scopePreserved: true, errors, queries };
  await writeFile(output + '/report.json', JSON.stringify(report, null, 2));
  console.log(JSON.stringify({ ...report, queries: queries.length }));
} finally { await browser.close(); }
