import { chromium, expect } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';

const base = process.env.LANDING_BASE_URL || 'http://127.0.0.1:5187';
const output = 'review/landing-redesign-20260913';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const errors = [], checks = [];
try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 950 }, reducedMotion: 'reduce' });
    const page = await context.newPage();
    page.on('pageerror', error => errors.push(error.message));
    const requests = [];
    page.on('request', request => requests.push(request.url()));
    await page.goto(base + '/');
    await expect(page.getByRole('heading', { name: 'Find your place in football.' })).toBeVisible();
    await expect(page.getByLabel('Email', { exact: true })).toHaveAttribute('autocomplete', 'username');
    await expect(page.getByLabel('Password', { exact: true })).toHaveAttribute('autocomplete', 'current-password');
    expect(requests.some(url => url.includes('LandingPlayground'))).toBe(false);
    expect(await page.locator('.role-discovery-route').evaluate(element => getComputedStyle(element).animationName)).toBe('none');
    for (const [name, scene] of [['I run a club', 'club'], ['I love the game', 'supporter'], ['I want to play', 'player']]) {
        await page.getByRole('tab', { name }).click();
        await expect(page.locator('[data-role-scene]')).toHaveCount(1);
        await expect(page.locator('.landing-role-copy')).toHaveCount(1);
        await expect(page.locator('[data-role-scene]')).toHaveAttribute('data-role-scene', scene);
    }
    await page.route('**/api/auth/login', route => route.fulfill({ status: 401, contentType: 'application/json', body: JSON.stringify({ message: 'Invalid email or password.' }) }));
    await page.getByLabel('Email', { exact: true }).fill('landing-check@example.test');
    await page.getByLabel('Password', { exact: true }).fill('synthetic-test-password');
    await page.getByRole('button', { name: 'Log in', exact: true }).click();
    await expect(page.getByRole('alert')).toContainText('Invalid email or password.');
    await expect(page.getByRole('button', { name: 'Log in', exact: true })).toBeEnabled();
    expect(new URL(page.url()).pathname).toBe('/');
    checks.push('Accessible login fields and recoverable mocked login failure; Playground is not loaded before discovery; reduced motion');

    for (const width of [1440, 390]) {
        await page.setViewportSize({ width, height: 950 });
        const viewport = page.locator('[data-landing-map-viewport]');
        await viewport.scrollIntoViewIfNeeded();
        const originalSize = await viewport.boundingBox();
        await page.getByRole('button', { name: /^Open filters/ }).click();
        const filterDialog = page.getByRole('dialog', { name: 'Find football clubs' });
        await expect(filterDialog).toBeVisible();
        const filter = page.getByLabel('Simple map filters');
        await expect(filter).toBeVisible();
        const a = await filter.boundingBox();
        expect(a.height).toBeGreaterThan(700);
        expect(a.x).toBeGreaterThanOrEqual(0);
        expect(a.y + a.height).toBeLessThanOrEqual(950);
        expect(await page.evaluate(() => document.body.style.overflow)).toBe('hidden');
        await filter.getByLabel('Club type', { exact: true }).selectOption('PRIVATE_ACADEMY');
        await page.keyboard.press('Escape');
        await expect(filterDialog).toHaveCount(0);
        await expect(page.getByRole('button', { name: /^Open filters/ })).toBeFocused();
        await page.getByRole('button', { name: /^Open filters/ }).click();
        await expect(filter.getByLabel('Club type', { exact: true })).toHaveValue('PRIVATE_ACADEMY');
        await filter.getByLabel('Club type', { exact: true }).selectOption('');
        await filter.getByLabel('Country', { exact: true }).fill('Georgia');
        await filter.getByRole('button', { name: 'Georgia GE', exact: true }).click();
        await expect(filter.getByLabel('City', { exact: true })).toBeEnabled();
        await filter.getByLabel('Age group', { exact: true }).selectOption('U16');
        await filter.getByLabel('Gender', { exact: true }).selectOption('Girls');
        await filter.getByLabel('Level', { exact: true }).selectOption('Academy');
        await page.screenshot({ path: output + `/filters-${width}.png` });
        const show = filter.getByRole('button', { name: 'Show results', exact: true });
        const applied = page.waitForRequest(request => request.url().includes('/map/nearby') && request.url().includes('U16'));
        await show.scrollIntoViewIfNeeded(); await show.click();
        const appliedUrl = (await applied).url();
        expect(appliedUrl).toContain('gender=FEMALE');
        expect(appliedUrl).toContain('Academy');
        await expect(filter).not.toBeVisible();
        const newSize = await viewport.boundingBox();
        expect(newSize.width).toBe(originalSize.width);
        expect(newSize.height).toBe(originalSize.height);
        await page.getByRole('button', { name: /^Open filters/ }).click();
        await filter.getByRole('button', { name: /^(Choose|Change) on map$/ }).click();
        await expect(filterDialog).toHaveCount(0);
        await expect(page.getByRole('status').filter({ hasText: 'Choose your starting point on the map' })).toBeVisible();
        await page.getByRole('button', { name: 'Cancel picking start' }).click();
        await page.getByRole('button', { name: /^Open filters/ }).click();
        await filter.getByRole('button', { name: 'Reset map filters' }).click();
        if (await filterDialog.count()) await page.keyboard.press('Escape');
        await page.screenshot({ path: output + `/map-${width}.png` });
        expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    }
    checks.push('Distinct role scenes; desktop and mobile filter dialog, focus restoration, draft retention, country/city dependency, real filter requests, pick-location handoff, unchanged map size and no overflow');

    await page.getByRole('button', { name: 'Open Playground' }).click();
    const dialog = page.getByRole('dialog');
    await expect(dialog).toBeVisible();
    await page.keyboard.press('Tab');
    expect(await page.evaluate(() => !!document.activeElement.closest('dialog'))).toBe(true);
    const pitch = dialog.locator('canvas');
    const rect = await pitch.boundingBox();
    const touch = await context.newCDPSession(page);
    const start = { x: rect.x + rect.width * 160 / 980, y: rect.y + rect.height / 2 };
    await touch.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [start] });
    await touch.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: start.x - rect.width * 110 / 980, y: start.y }] });
    await touch.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
    await expect(dialog.getByRole('status')).toContainText('That’s a goal!', { timeout: 6000 });
    await dialog.getByRole('button', { name: 'Next ball', exact: true }).click();
    await pitch.focus(); await pitch.press('ArrowUp');
    await expect(dialog.getByLabel('Shot angle')).toHaveValue('-5');
    await pitch.press('Space');
    await dialog.getByRole('button', { name: 'Pause', exact: true }).click();
    await expect(dialog.getByRole('status')).toContainText('Taking a breather');
    await dialog.getByRole('button', { name: 'Resume', exact: true }).click();
    await page.keyboard.press('Escape');
    await expect(dialog).toHaveCount(0);
    await expect(page.getByRole('button', { name: 'Open Playground' })).toBeFocused();
    expect(await page.evaluate(() => document.body.style.overflow)).not.toBe('hidden');
    checks.push('Touch drag, keyboard aim and shot, pause/resume, modal focus containment, Escape and cleanup');
    expect(errors).toEqual([]);
    await writeFile(output + '/interaction-report.json', JSON.stringify({ passed: true, checks, errors }, null, 2));
    console.log(JSON.stringify({ passed: true, checks, errors }));
} finally { await browser.close(); }
