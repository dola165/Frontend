import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';

const output = 'review/recruitment-design-20260914';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
const base = 'http://localhost:5300/e2e/fixtures/recruitment-preview.html';
await page.goto(`${base}?tab=applications&lang=en`);
await page.getByRole('button', { name: 'Review', exact: true }).first().waitFor();
await page.screenshot({ path: `${output}/applications-desktop.png`, fullPage: true });
await page.getByRole('button', { name: 'Review', exact: true }).first().click();
await page.getByRole('dialog', { name: 'Luka Trialist' }).waitFor();
await page.screenshot({ path: `${output}/application-review.png` });
await page.getByRole('button', { name: 'Accept', exact: true }).click();
await page.getByRole('dialog', { name: 'Accept application' }).waitFor();
await page.getByLabel(/Message to the applicant/).fill('Thursday at 18:00. Bring boots.');
await page.screenshot({ path: `${output}/decision-note.png` });
await page.getByRole('button', { name: 'Cancel', exact: true }).click();
await page.goto(`${base}?tab=tryouts&lang=en`);
await page.getByRole('heading', { name: 'U17 Open Tryout' }).waitFor();
await page.screenshot({ path: `${output}/tryouts-desktop.png`, fullPage: true });
await page.getByRole('button', { name: 'Post a tryout', exact: true }).click();
await page.getByRole('dialog', { name: 'New tryout' }).waitFor();
await page.screenshot({ path: `${output}/tryout-editor.png` });
await page.setViewportSize({ width: 390, height: 844 });
await page.screenshot({ path: `${output}/tryout-editor-mobile.png` });
await page.getByRole('button', { name: 'Cancel', exact: true }).click();
await page.screenshot({ path: `${output}/tryouts-mobile.png`, fullPage: true });
const mobileWidth = await page.evaluate(() => ({ viewport: innerWidth, document: document.documentElement.scrollWidth }));
if (mobileWidth.document > mobileWidth.viewport) throw new Error(`Page overflow: ${JSON.stringify(mobileWidth)}`);
await page.goto(`${base}?tab=journey&lang=en`);
await page.getByRole('heading', { name: 'Your club journey' }).waitFor();
await page.screenshot({ path: `${output}/journey-mobile.png`, fullPage: true });
await page.setViewportSize({ width: 1440, height: 1050 });
await page.goto(`${base}?tab=applications&lang=ka`);
await page.getByRole('button', { name: 'განხილვა', exact: true }).first().waitFor();
await page.screenshot({ path: `${output}/applications-ka.png`, fullPage: true });
await browser.close();
if (errors.length) throw new Error(errors.join('\n'));
console.log('Recruitment preview passed: desktop and mobile rendering, review-to-note handoff, editor, player journey, Georgian copy, no page overflow or runtime errors.');
