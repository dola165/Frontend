import { chromium, expect } from '@playwright/test';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
const baseUrl = process.env.ATLAS_BASE_URL || 'http://127.0.0.1:5187';
const output = 'review/mobile-map-repair';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 360, height: 437 }, hasTouch: true, geolocation: { longitude: 44.82, latitude: 41.714 }, permissions: ['geolocation'] });
page.setDefaultTimeout(15000);
const markers = Array.from({ length: 15 }, (_, i) => ({ entityId: i + 1, entityType: 'CLUB', title: `Community Football Club ${String(i + 1).padStart(2, '0')}`, subtitle: 'Grassroots', clubName: 'Community Football Club', clubId: i + 1, latitude: 41.7151 + i * .0001, longitude: 44.8271, distanceKm: i / 10, members: 30, followers: 50, verified: true, addressText: 'Tbilisi Community Pitch', status: 'ACTIVE' }));
await page.route(url => url.pathname.startsWith('/api/'), route => {
    if (new URL(route.request().url()).pathname.endsWith('/map/nearby')) return route.fulfill({ json: { content: markers, page: 0, size: 100, totalElements: markers.length, resultsLimited: false } });
    if (route.request().url().includes('/auth/refresh')) return route.fulfill({ status: 401, json: {} });
    return route.fulfill({ json: {} });
});
let networkRequests = 0;
await page.route('**/interpreter', route => { networkRequests++; return route.fulfill({ status: 503, json: {} }); });
const errors = []; page.on('pageerror', error => errors.push(error.message));
try {
    await page.goto(baseUrl + '/e2e/fixtures/map-discovery.html');
    await page.addStyleTag({ content: await readFile('src/android/android.css', 'utf8') });
    await page.evaluate(() => document.documentElement.classList.add('android-app'));
    await expect.poll(() => page.evaluate(() => Boolean(window.gkTestMap?.isStyleLoaded())), { timeout: 30000 }).toBe(true);
    await page.getByRole('button', { name: 'Toggle nearby results' }).tap();
    const results = page.getByRole('complementary', { name: 'Nearby results' });
    await expect(results.getByRole('listitem')).toHaveCount(15);
    const geometry = await results.evaluate(el => ({ height: el.clientHeight, scrollHeight: el.scrollHeight, headerHeight: el.querySelector('header').clientHeight, listOverflow: getComputedStyle(el.querySelector('.atlas-results-scroll')).overflowY }));
    expect(geometry.height - geometry.headerHeight).toBeGreaterThan(220);
    expect(geometry.listOverflow).toBe('visible');
    expect(geometry.scrollHeight).toBeGreaterThan(geometry.height);
    const first = results.getByRole('listitem').first();
    await expect(first.getByRole('link', { name: 'View club' })).toBeInViewport({ ratio: 1 });
    await expect(first.getByRole('button', { name: /Walk to/ })).toBeInViewport({ ratio: 1 });
    await page.screenshot({ path: `${output}/results-360x437.png` });
    await first.getByRole('button', { name: /Walk to/ }).tap();
    const walking = page.getByRole('complementary', { name: 'Walking directions' });
    await expect(walking.getByRole('alert')).toContainText('busy');
    await walking.getByRole('button', { name: 'My location', exact: true }).tap();
    await expect.poll(() => networkRequests).toBe(2);
    await expect(walking.getByRole('button', { name: 'Close walking directions' })).toBeInViewport({ ratio: 1 });
    await page.screenshot({ path: `${output}/walking-error-360x437.png` });
    await walking.getByRole('button', { name: 'Close walking directions' }).tap();
    await page.getByRole('button', { name: 'Toggle nearby results' }).tap();
    await results.getByRole('listitem').first().getByRole('link', { name: 'View club' }).tap();
    await expect.poll(() => page.evaluate(() => window.gkTestLocation)).toBe('/clubs/1');
    await results.getByRole('listitem').last().getByRole('link', { name: 'View club' }).tap();
    await expect.poll(() => page.evaluate(() => window.gkTestLocation)).toBe('/clubs/15');
    await expect(results.getByRole('button', { name: 'Close results' })).toBeInViewport({ ratio: 1 });
    await results.getByRole('button', { name: 'Close results' }).tap();
    await page.getByRole('button', { name: 'Toggle filters' }).tap();
    const filters = page.getByRole('complementary', { name: 'Simple map filters' });
    await expect(filters.getByRole('button', { name: 'Show results', exact: true })).toBeInViewport({ ratio: 1 });
    const filterContentHeight = await filters.locator(':scope > div').evaluate(el => el.clientHeight);
    expect(filterContentHeight).toBeGreaterThan(200);
    await filters.getByLabel('Country', { exact: true }).tap();
    await filters.getByRole('button', { name: 'Show results', exact: true }).tap();
    expect(errors).toEqual([]);
    await writeFile(`${output}/overlays-360x437.json`, JSON.stringify({ geometry, filterContentHeight, firstClubTap: true, lastClubTap: true, walkingRetryTap: true, filtersApplyTap: true, errors }, null, 2));
    console.log('PASS: Android CSS at360x437,15 results, first/last club links, walkingretry andfilterapply via touch');
} catch (error) {
    await page.screenshot({ path: `${output}/overlays-failure.png` });
    console.log((await page.locator('body').innerText()).slice(0, 2000));
    throw error;
} finally { await browser.close(); }
