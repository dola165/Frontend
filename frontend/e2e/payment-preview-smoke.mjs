import { chromium, expect } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
const origin = process.env.PAYMENT_PREVIEW_URL || 'http://127.0.0.1:5278';
const output = 'review/payment-preview-20260914';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const result = { source: 'Existing backend catalog and campaigns', origin, writes: [], errors: [], checks: [] };
try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    page.on('pageerror', error => result.errors.push(error.message));
    page.on('request', request => {
        if (/\/api\/(store|campaigns|clubs)/.test(request.url()) && !['GET', 'HEAD', 'OPTIONS'].includes(request.method())) result.writes.push({ url: request.url(), method: request.method() });
    });
    await page.addInitScript(() => { localStorage.setItem('i18nextLng', 'en'); localStorage.setItem('theme-preference', 'dark'); });
    const capture = async name => {
        await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }));
        await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
        await page.screenshot({ path: `${output}/${name}.png`, fullPage: true });
    };
    await page.goto(`${origin}/store`);
    await expect(page.getByText('Test payments are on', { exact: true })).toBeVisible();
    const product = page.locator('.store-product-card').filter({ hasNot: page.locator('.store-stock-badge') }).first();
    await product.locator('.store-card-main').click();
    await page.getByRole('button', { name: 'Add to cart', exact: true }).click();
    await page.getByRole('link', { name: 'Open cart', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Simulate checkout', exact: true })).toBeVisible();
    expect(await page.locator('.payment-preview').evaluate(el => getComputedStyle(el).backgroundColor)).toBe('rgb(213, 223, 236)');
    await capture('cart-desktop');
    const initialCart = await page.evaluate(() => localStorage.getItem('gk.store.cart.v1'));
    await page.getByLabel('Declined payment', { exact: true }).check();
    await page.getByRole('button', { name: 'Simulate checkout', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Test payment declined', exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Try another test', exact: true }).click();
    await page.getByRole('button', { name: 'Simulate checkout', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Test payment successful', exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Test a refund', exact: true }).click();
    await page.getByRole('button', { name: 'Confirm test refund', exact: true }).click();
    await expect(page.getByText(/Test refunded/)).toBeVisible();
    await page.reload();
    await expect(page.getByRole('button', { name: 'Simulate checkout', exact: true })).toBeVisible();
    await page.locator('.payment-preview-history summary').click();
    await expect(page.getByText(/Test refunded/)).toBeVisible();
    expect(await page.evaluate(() => localStorage.getItem('gk.store.cart.v1'))).toBe(initialCart);
    await page.setViewportSize({ width: 390, height: 844 });
    await capture('cart-mobile');
    result.checks.push('actual cart: decline, retry, success, refund, reload, cart retained, readable desktop/mobile');
    await page.goto(`${origin}/campaigns`);
    await expect(page.locator('.campaign-card').first()).toBeVisible();
    await page.locator('.campaign-card h2 a').first().click();
    await expect(page.getByRole('button', { name: 'Simulate contribution', exact: true })).toBeVisible();
    const before = await page.locator('.campaign-progress').innerText();
    await page.getByLabel(/Test contribution amount/).fill('12.34');
    await page.setViewportSize({ width: 1440, height: 1000 });
    await capture('campaign-desktop');
    await page.getByRole('button', { name: 'Simulate contribution', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Test payment successful', exact: true })).toBeVisible();
    expect(await page.locator('.campaign-progress').innerText()).toBe(before);
    await page.setViewportSize({ width: 390, height: 844 });
    await capture('campaign-mobile');
    result.checks.push('actual campaign: correct currency/amount, successful contribution, unchanged published progress, desktop/mobile');
    expect(result.errors).toEqual([]);
    expect(result.writes).toEqual([]);
    await writeFile(`${output}/results.json`, JSON.stringify(result, null, 2));
    console.log(JSON.stringify(result, null, 2));
} finally { await browser.close(); }
