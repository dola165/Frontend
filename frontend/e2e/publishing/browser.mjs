// Run only against the local synthetic fixture, never a live account.
import { chromium } from 'playwright';
import { expect } from '@playwright/test';
import fs from 'node:fs/promises';
const out = process.env.PUBLISHING_EVIDENCE_DIR;
if (!out) throw Error('PUBLISHING_EVIDENCE_DIR is required');
await fs.mkdir(out, { recursive: true });
const origin = 'http://127.0.0.1:5207';
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const results = [];
try {
for (const width of [1920, 390]) for (const theme of ['light','dark']) {
    const context = await browser.newContext({ viewport: { width, height: width === 390 ? 844 : 1080 }, reducedMotion: 'reduce', colorScheme: theme });
    const external = [], errors = [];
    await context.route('**/*', route => { if (new URL(route.request().url()).origin === origin) return route.continue(); external.push(route.request().url()); return route.abort(); });
    const page = await context.newPage(); page.on('pageerror', error => errors.push(error.message));
    await page.goto(origin + '/e2e/publishing/index.html?theme=' + theme);
    const card = page.locator('article.feed-post').filter({ hasText: 'Training update 16:' });
    await page.getByRole('link', { name: 'Following', exact: true }).click();
    await page.getByRole('button', { name: 'Load more posts' }).click();
    await expect(card).toBeVisible();
    await card.getByRole('button', { name: /^Comment,/ }).click();
    const draft = card.getByRole('textbox', { name: /^Write a comment/ });
    await draft.fill('Meet by the east gate');
    await card.getByLabel(/Actions for post/).click();
    const returnY = await page.evaluate(() => window.scrollY);
    await card.getByRole('link', { name: 'Open post', exact: true }).click();
    await expect(page.getByRole('link', { name: 'Back to Home' })).toHaveAttribute('href', '/home?view=following');
    await page.getByRole('button', { name: 'Comment', exact: true }).click();
    await expect(page.getByRole('textbox', { name: /^Write a comment/ })).toHaveValue('Meet by the east gate');
    await page.getByRole('link', { name: 'Back to Home' }).click();
    await expect(card).toBeVisible();
    // A fresh current page may be shorter (collapsed comments or removed content).
    const restoredY = await page.evaluate(y => Math.min(y, Math.max(0, document.documentElement.scrollHeight - innerHeight)), returnY);
    await expect.poll(() => page.evaluate(() => window.scrollY)).toBeCloseTo(restoredY, -1);
    await expect(page.getByRole('button', { name: 'Newer posts' })).toBeVisible();
    await expect(page.getByText('Training update 20:', { exact: false })).toHaveCount(0);
    const lower = page.locator('article.feed-post').filter({ hasText: 'Training update 14:' });
    await lower.getByLabel(/Actions for post/).click();
    const deeperReturn = await page.evaluate(() => window.scrollY);
    await lower.getByRole('link', { name: 'Open post', exact: true }).click();
    await page.getByRole('link', { name: 'Back to Home' }).click();
    await expect(lower).toBeVisible();
    await expect.poll(() => page.evaluate(() => window.scrollY)).toBeCloseTo(deeperReturn, -1);

    await card.getByRole('button', { name: /^Comment,/ }).click(); await expect(draft).toHaveValue('Meet by the east gate');
    await card.getByRole('button', { name: /^Open media/ }).click();
    let dialog = page.getByRole('dialog'); await expect(dialog.getByAltText('Post media in viewer')).toBeVisible();
    await expect(dialog.getByRole('textbox', { name: /^Write a comment/ })).toHaveValue('Meet by the east gate');
    await dialog.getByRole('button', { name: 'Post comment', exact: true }).click();
    await expect(dialog.getByRole('button', { name: 'Retry comment' })).toBeVisible();
    await dialog.getByRole('button', { name: 'Retry comment' }).click();
    await expect(dialog.getByText('Meet by the east gate', { exact: true })).toHaveCount(1);
    await expect(dialog.getByRole('textbox', { name: /^Write a comment/ })).toHaveValue('');
    const own = dialog.getByRole('article', { name: 'Comment by Synthetic coach' });
    await own.getByRole('button', { name: 'Reply', exact: true }).click();
    await dialog.getByRole('textbox', { name: /^Write a comment/ }).fill('Reply retained');
    await dialog.getByRole('button', { name: 'Cancel reply' }).click();
    await expect(dialog.getByRole('textbox', { name: /^Write a comment/ })).toHaveValue('Reply retained');
    await own.getByRole('button', { name: 'Edit', exact: true }).click();
    await own.getByRole('textbox', { name: 'Edit comment' }).fill('Cancelled edit');
    await page.evaluate(() => window.dispatchEvent(new Event('pageshow')));
    await expect(page.getByRole('dialog').getByRole('textbox', { name: 'Edit comment' })).toHaveValue('Cancelled edit');
    await own.getByRole('button', { name: 'Cancel', exact: true }).click();
    await expect(own.getByText('Meet by the east gate')).toBeVisible();
    await own.getByRole('button', { name: 'Edit', exact: true }).click();
    await own.getByRole('textbox', { name: 'Edit comment' }).fill('Corrected after explicit reload');
    await page.evaluate(() => window.dispatchEvent(new Event('synthetic-publishing-conflict')));
    await own.getByRole('button', { name: 'Save comment' }).click();
    await expect(own.getByRole('alert')).toBeVisible();
    await own.getByRole('button', { name: 'Reload comment' }).click();
    await expect(page.getByRole('dialog').getByRole('textbox', { name: 'Edit comment' })).toHaveValue('Corrected after explicit reload');
    await own.getByRole('button', { name: 'Save comment' }).click();
    await expect(own.getByText('Corrected after explicit reload')).toBeVisible();
    await own.getByRole('button', { name: 'Like 0', exact: true }).click();
    await expect(own.getByRole('button', { name: 'Like 1', exact: true })).toHaveAttribute('aria-pressed','true');
    await page.screenshot({ path: out + '/' + width + '-' + theme + '-media-comments.png' });
    await own.getByRole('button', { name: 'Delete', exact: true }).click();
    await own.getByRole('button', { name: 'Delete comment', exact: true }).click();
    await expect(dialog.getByText('Comment removed', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Close post viewer' }).click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await card.getByRole('button', { name: 'Share', exact: true }).click();
    dialog = page.getByRole('dialog', { name: 'Share post' });
    await dialog.getByLabel('Say something about this post').fill('Team reminder');
    await dialog.getByRole('button', { name: 'Share now' }).click();
    dialog = page.getByRole('dialog', { name: 'Post shared' });
    await expect(dialog.getByText('Shared to your profile', { exact: true })).toBeVisible();
    await dialog.getByRole('button', { name: 'Done' }).click();
    await card.getByLabel(/Actions for post/).click(); await card.getByRole('button', { name: 'Report post' }).click();
    dialog = page.getByRole('dialog', { name: 'Report post' });
    await dialog.getByLabel('Spam or unwanted promotion').check();
    await dialog.getByRole('button', { name: 'Send report' }).click();
    await expect(dialog.getByRole('link', { name: 'View report receipt' })).toHaveAttribute('href','/reports?itemId=55');
    await dialog.getByRole('link', { name: 'View report receipt' }).click();
    await expect(page.getByRole('heading', { name: 'Report #55 · Post' })).toBeVisible();
    await page.screenshot({ path: out + '/' + width + '-' + theme + '-receipt.png' });
    await page.getByRole('navigation', { name: 'Synthetic controls' }).getByRole('link', { name: 'Home', exact: true }).click();
    await page.getByRole('link', { name: 'Following', exact: true }).click();
    await page.getByRole('button', { name: 'Load more posts' }).click();
    await card.getByLabel(/Actions for post/).click(); await card.getByRole('button', { name: 'Hide post' }).click();
    await page.getByRole('button', { name: 'Undo', exact: true }).click(); await expect(card).toBeVisible();
    await card.getByRole('button', { name: /^Comment,/ }).click(); await expect(draft).toHaveValue('Reply retained');
    await page.screenshot({ path: out + '/' + width + '-' + theme + '-feed-return.png' });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.getByRole('button', { name: 'Revoke post access' }).click();
    await card.getByRole('button', { name: /^Open media/ }).click();
    await expect(page.getByRole('alert')).toContainText('unavailable');
    await expect(page.getByAltText('Post media in viewer')).toHaveCount(0);
    expect(errors).toEqual([]);
    results.push({ width, theme, result: 'passed', publishingRecovery: ['foreground edit retained', 'conflict reload retained text and adopted current version'], returnScroll: { requested: returnY, restored: restoredY, deeperReturn }, externalRequestsBlocked: external.length, pageErrors: errors });
    console.log(JSON.stringify(results.at(-1))); await context.close();
}
} finally { await fs.writeFile(out + '/browser-results.json', JSON.stringify(results,null,2)); await browser.close(); }
