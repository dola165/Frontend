import { chromium, expect } from '@playwright/test';
import { writeFile } from 'node:fs/promises';
const output='review/squads-redesign-20260914';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1600,height:1000}});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.route('**/*',route=>route.request().url().startsWith('http://127.0.0.1:5300') ? route.continue() : route.abort());
const base='http://127.0.0.1:5300/e2e/fixtures/squads-preview.html';
const capture=async(name)=>{await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);await page.screenshot({path:`${output}/${name}.png`,fullPage:false});};
try {
 await page.goto(`${base}?view=player-cards&lang=en`);
 await expect(page.locator('.prc-row')).toHaveCount(3);
 await capture('player-cards-desktop');
 await page.getByRole('button',{name:'Create Card',exact:true}).click();
 const dialog=page.getByRole('dialog');
 await dialog.getByLabel('Full Name',{exact:true}).fill('Nika Metreveli');
 await dialog.getByLabel('Birth Year',{exact:true}).fill(String(new Date().getFullYear()-18));
 await dialog.getByLabel('Position',{exact:true}).selectOption('CENTRAL_MIDFIELDER');
 await dialog.getByLabel('Jersey Number',{exact:true}).fill('8');
 await dialog.getByLabel('Squad',{exact:true}).selectOption('71105');
 await capture('player-card-editor-desktop');
 await dialog.getByRole('button',{name:'Cancel',exact:true}).click();
 await dialog.getByRole('button',{name:'Keep editing',exact:true}).click();
 await expect(dialog.getByLabel('Full Name',{exact:true})).toHaveValue('Nika Metreveli');
 await dialog.getByRole('button',{name:'Cancel',exact:true}).click();
 await dialog.getByRole('button',{name:'Discard',exact:true}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await page.setViewportSize({width:390,height:844});
 await page.goto(`${base}?view=player-cards&lang=en`);
 await expect(page.locator('.prc-row')).toHaveCount(3);
 await capture('player-cards-mobile');
 await page.getByRole('button',{name:'Create Card',exact:true}).click();
 await dialog.getByLabel('Full Name',{exact:true}).fill('Nika Metreveli');
 await dialog.getByLabel('Birth Year',{exact:true}).fill(String(new Date().getFullYear()-12));
 await dialog.getByLabel('Position',{exact:true}).selectOption('CENTRAL_MIDFIELDER');
 await dialog.getByLabel('Jersey Number',{exact:true}).fill('8');
 await dialog.getByLabel('Squad',{exact:true}).selectOption('71102');
 await dialog.getByLabel('Parent / Guardian Email',{exact:true}).fill('guardian@example.com');
 await expect(dialog.getByRole('button',{name:'Create Card',exact:true})).toBeInViewport();
 await capture('player-card-editor-mobile');
 await dialog.locator('.prf-body').evaluate(el=>el.scrollTop=0);
 await capture('player-card-editor-mobile-top');
 await dialog.getByRole('button',{name:'Cancel',exact:true}).click();
 await dialog.getByRole('button',{name:'Discard',exact:true}).click();
 await page.goto(`${base}?view=squads&lang=en`);
 await page.getByRole('button',{name:'Add players',exact:true}).click();
 await expect(page.locator('.prf-player-option').first()).toBeVisible();
 await capture('add-players-mobile');
 await page.getByRole('button',{name:/No account yet/}).click();
 await expect(page.locator('.prf-card-dialog')).toBeVisible();
 await page.getByRole('dialog',{name:'Create Player Card',exact:true}).getByRole('button',{name:'Cancel',exact:true}).click();
 await expect(page.locator('.prf-picker')).toBeVisible();
 await page.setViewportSize({width:1600,height:1000});
 await capture('add-players-desktop');
 await writeFile(`${output}/player-forms-results.json`,JSON.stringify({errors},null,2));
 if(errors.length)throw new Error(errors.join('\n'));
 console.log('Player-card desktop/mobile and nested picker inspection passed.');
}finally{await browser.close();}
